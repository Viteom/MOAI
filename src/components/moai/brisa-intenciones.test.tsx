import { it, expect, vi } from 'vitest';
import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import { BuscarConBrisa } from './brisa-intenciones';
import type { Api, Perfil } from '@/lib/api';
import { VERSION_MEMORIA } from '@/lib/brisa-intenciones';
import { VERSION_LENGUAJE } from '@/lib/lenguaje-brisa';
const perfil = { nombre: 'Rosa', lugar: { id: 'l1', zona: 'Medellín', ciudad: '05001' } } as Perfil;
const ok = <T,>(datos: T) => vi.fn(async () => ({ ok: true as const, datos }));
const propuesta = { id: 'propuesta', plan: { id: 'plan', titulo: 'Caminata publicada', cuando: '2026-10-24T15:00:00Z', lugarPublico: 'Parque', zona: 'Medellín', costo: 'gratis' }, motivo: 'Actividad indicada en esta búsqueda.', venceEn: '2026-10-20T15:15:00Z' };
const resultado = { lugarId: 'l1', zona: 'Medellín', criterios: { tipos: ['caminar'], dias: [6], soloGratis: false, fuentes: [] }, propuestas: [propuesta], mensaje: 'Encontré este plan.' };
const a = (extra: Partial<Api> = {}) => ({ modeloBrisa: ok({ disponible: false, proveedor: 'Gemini', soloPruebas: true, version: 'beta' }), memoriaBrisa: ok({ memoria: null }), buscarConBrisa: ok(resultado), confirmarPropuestaBrisa: ok({ hecha: true, planId: 'plan' }), descartarPropuestaBrisa: ok({ ok: true }), ...extra }) as unknown as Api;
const buscar = async () => { const b = await screen.findByRole('button', { name: 'Buscar planes' }); await waitFor(() => expect(b).toBeEnabled()); fireEvent.change(screen.getByLabelText('Qué te gustaría hacer'), { target: { value: 'Busca caminar el sábado' } }); fireEvent.click(b); };
it('Gemini necesita autorización por frase y deja la interpretación para revisar, sin buscar ni sumarse automáticamente', async () => {
  let resolver!: (r: Awaited<ReturnType<Api['interpretarConBrisa']>>) => void;
  const interpretar = vi.fn<Api['interpretarConBrisa']>(() => new Promise(r => { resolver = r; }));
  const api = a({ modeloBrisa: ok({ disponible: true, proveedor: 'Gemini', soloPruebas: true, version: VERSION_LENGUAJE }), interpretarConBrisa: interpretar });
  render(<BuscarConBrisa api={api} perfil={perfil} ir={vi.fn()} volver={vi.fn()}/>);
  fireEvent.click(screen.getByText('Entender mi idea con Gemini · beta'));
  const campo = screen.getByLabelText('Qué te gustaría hacer');
  fireEvent.change(campo, { target: { value: 'Tengo libre el sábado y quisiera estirar las piernas' } });
  const boton = await screen.findByRole('button', { name: 'Interpretar frase ficticia' });
  expect(boton).toBeDisabled();
  fireEvent.click(screen.getByLabelText(/Confirmo que esta frase es ficticia/));
  fireEvent.change(campo, { target: { value: 'Tengo libre el sábado y quisiera estirar las piernas con alguien' } });
  expect(boton).toBeDisabled();
  fireEvent.click(screen.getByLabelText(/Confirmo que esta frase es ficticia/)); fireEvent.click(boton);
  expect(screen.getByRole('button', { name: 'Buscar planes' })).toBeDisabled();
  fireEvent.submit(campo.closest('form')!);
  expect(api.buscarConBrisa).not.toHaveBeenCalled();
  resolver({ ok: true, datos: { consulta: 'caminar el sábado', proveedor: 'Gemini', soloPruebas: true } });
  expect(await screen.findByText(/Así entendí tu idea/)).toHaveTextContent('caminar el sábado');
  expect(campo).toHaveValue('caminar el sábado');
  expect(interpretar).toHaveBeenCalledWith({ frase: 'Tengo libre el sábado y quisiera estirar las piernas con alguien', autorizo: VERSION_LENGUAJE, datosFicticios: true });
  expect(api.buscarConBrisa).not.toHaveBeenCalled(); expect(api.confirmarPropuestaBrisa).not.toHaveBeenCalled();
  expect(screen.getByLabelText(/Confirmo que esta frase es ficticia/)).not.toBeChecked();
});
it('un fallo del proveedor no sustituye la intención ni busca silenciosamente', async () => {
  const api = a({ modeloBrisa: ok({ disponible: true, proveedor: 'Gemini', soloPruebas: true, version: VERSION_LENGUAJE }), interpretarConBrisa: vi.fn(async () => ({ ok: false as const, error: 'Gemini no está disponible.' })) });
  render(<BuscarConBrisa api={api} perfil={perfil} ir={vi.fn()} volver={vi.fn()}/>);
  fireEvent.click(screen.getByText('Entender mi idea con Gemini · beta'));
  fireEvent.change(screen.getByLabelText('Qué te gustaría hacer'), { target: { value: 'Busca caminar el sábado' } });
  const boton = await screen.findByRole('button', { name: 'Interpretar frase ficticia' });
  fireEvent.click(screen.getByLabelText(/Confirmo que esta frase es ficticia/)); fireEvent.click(boton);
  expect(await screen.findByRole('alert')).toHaveTextContent('Gemini no está disponible.');
  expect(screen.getByLabelText('Qué te gustaría hacer')).toHaveValue('Busca caminar el sábado');
  expect(api.buscarConBrisa).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('button', { name: 'Buscar planes' }));
  expect(await screen.findByText('Caminata publicada')).toBeInTheDocument();
});
it('busca, explica y permite cancelar; solo ejecuta tras confirmación y evita doble envío', async () => {
  let resolver!: (v: any) => void;
  const confirmar = vi.fn(() => new Promise<any>(r => { resolver = r; }));
  const api = a({ confirmarPropuestaBrisa: confirmar });
  render(<BuscarConBrisa api={api} perfil={perfil} ir={vi.fn()} volver={vi.fn()}/>);
  expect(api.buscarConBrisa).not.toHaveBeenCalled();
  await buscar();
  expect(await screen.findByText('Actividad indicada en esta búsqueda.')).toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: 'Revisar para sumarme' }));
  fireEvent.click(screen.getByRole('button', { name: 'Cancelar' }));
  expect(confirmar).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('button', { name: 'Revisar para sumarme' }));
  const boton = screen.getByRole('button', { name: 'Sí, confirmar asistencia' });
  expect(boton).toHaveFocus(); fireEvent.click(boton); fireEvent.click(boton);
  expect(confirmar).toHaveBeenCalledTimes(1);
  resolver({ ok: true, datos: { hecha: true, planId: 'plan' } });
  expect(await screen.findByText('Te sumaste al plan.')).toBeInTheDocument();
});
it('la memoria y la anticipación exigen permisos independientes; borrar no anuncia éxito si falla', async () => {
  const guardar = vi.fn(async (d: any) => ({ ok: true as const, datos: { memoria: { ...d, autorizadaEn: '2026-10-20T15:00:00Z', venceEn: '2026-11-19T15:00:00Z' } } }));
  const borrar = vi.fn().mockResolvedValueOnce({ ok: false, error: 'Sin conexión' }).mockResolvedValueOnce({ ok: true, datos: { memoria: null } });
  const api = a({ guardarMemoriaBrisa: guardar, borrarMemoriaBrisa: borrar });
  render(<BuscarConBrisa api={api} perfil={perfil} ir={vi.fn()} volver={vi.fn()}/>);
  fireEvent.click(await screen.findByText('Lo que Brisa puede recordar'));
  fireEvent.click(screen.getByLabelText('Caminar'));
  const autorizar = screen.getByRole('button', { name: 'Autorizar y recordar' });
  expect(autorizar).toBeDisabled();
  expect(screen.getByLabelText(/Mostrar propuestas/)).not.toBeChecked();
  fireEvent.click(screen.getByLabelText(/Autorizo guardar/)); fireEvent.click(autorizar);
  await waitFor(() => expect(guardar).toHaveBeenCalledWith(expect.objectContaining({ autorizo: true, anticipar: false, version: VERSION_MEMORIA, tipos: ['caminar'] })));
  expect(await screen.findByText(/Preferencias guardadas/)).toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: 'Olvidar preferencias' })); fireEvent.click(screen.getByRole('button', { name: 'Sí, olvidar preferencias' }));
  expect(await screen.findByRole('alert')).toHaveTextContent('Sin conexión');
  expect(screen.getByRole('button', { name: 'Sí, olvidar preferencias' })).toBeEnabled();
  fireEvent.click(screen.getByRole('button', { name: 'Sí, olvidar preferencias' }));
  expect(await screen.findByText(/Olvidé estas preferencias/)).toBeInTheDocument();
  expect(api.buscarConBrisa).not.toHaveBeenCalled();
});
it('muestra fallos y permite reintentar; ignora una respuesta después de desmontar', async () => {
  const buscarApi = vi.fn().mockResolvedValueOnce({ ok: false, error: 'Sin conexión' }).mockResolvedValueOnce({ ok: true, datos: resultado });
  const api = a({ buscarConBrisa: buscarApi });
  const vista = render(<BuscarConBrisa api={api} perfil={perfil} ir={vi.fn()} volver={vi.fn()}/>);
  await buscar(); expect(await screen.findByRole('alert')).toHaveTextContent('Sin conexión');
  await buscar(); expect(await screen.findByText('Caminata publicada')).toBeInTheDocument();
  vista.unmount();
  let responder!: (v: any) => void;
  const lenta = a({ buscarConBrisa: vi.fn(() => new Promise<any>(r => { responder = r; })) });
  const anterior = render(<BuscarConBrisa api={lenta} perfil={perfil} ir={vi.fn()} volver={vi.fn()}/>);
  await buscar(); anterior.unmount();
  render(<BuscarConBrisa api={a()} perfil={{ ...perfil, lugar: { ...perfil.lugar!, id: 'l2', zona: 'Bogotá' } }} ir={vi.fn()} volver={vi.fn()}/>);
  responder({ ok: true, datos: resultado });
  expect(await screen.findByText('Bogotá')).toBeInTheDocument();
  expect(screen.queryByText('Caminata publicada')).toBeNull();
});
